"""숫자 야구 (기본 버전) - 6차시: for 반복문, range, 문자열과 리스트 인덱싱

실행 방법: python 03_baseball_basic.py
"""

# =====================================================================
# 게임 규칙
#   컴퓨터가 1~9 중 "서로 다른" 숫자 3개를 순서대로 정해요. (예: 4 7 1)
#   플레이어가 세 자리 숫자를 말하면
#     - 숫자와 자리가 모두 같으면  → 스트라이크(S)
#     - 숫자는 있지만 자리가 다르면 → 볼(B)
#   9번 안에 3S(모두 맞힘)를 만들면 성공!
#
# 예) 정답 4 7 1, 입력 1 7 5
#     1번째 자리 '1' : 정답에 있지만 자리가 다름 → 볼
#     2번째 자리 '7' : 숫자도 자리도 같음       → 스트라이크
#     3번째 자리 '5' : 정답에 없음              → 아무것도 아님
#     결과: 1S 1B
# =====================================================================

import random

# random.sample(모음, 개수): 모음에서 "겹치지 않게" 개수만큼 뽑아 리스트로 돌려줌
# 문자열 "123456789"도 글자 하나하나를 고를 수 있는 모음이에요.
answer = random.sample("123456789", 3)   # 예: ['4', '7', '1']  (글자 리스트)

print("=== 숫자 야구 === 서로 다른 숫자 3개를 9번 안에 맞히세요!")
turn = 1                                 # 지금 몇 번째 도전인지

while turn <= 9:
    # list("175") → ['1', '7', '5'] : 문자열을 글자 하나씩 나눈 리스트로 바꿈
    guess = list(input(f"[{turn}회] 세 자리 숫자 > "))
    if len(guess) != 3:                  # != : 같지 않다
        print("3자리로 입력하세요!")
        continue

    strike = ball = 0
    # for i in range(3): i 가 0, 1, 2 로 바뀌면서 3번 반복
    # → 세 자리를 하나씩 비교하기 위해 "자리 번호(인덱스)"를 i 로 사용
    for i in range(3):
        if guess[i] == answer[i]:
            strike += 1          # 숫자와 자리가 모두 같음
        elif guess[i] in answer:
            ball += 1            # 숫자만 같음
    print(f"결과: {strike}S {ball}B")

    if strike == 3:
        print(f"{turn}번 만에 성공!")
        break
    turn += 1
else:
    # "".join(리스트): 리스트의 글자들을 이어 붙여 하나의 문자열로 만듦
    print("실패! 정답은", "".join(answer))
