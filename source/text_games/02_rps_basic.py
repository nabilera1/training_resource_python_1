"""가위바위보 (기본 버전) - 5차시: 리스트, 인덱스, random.choice, 나머지 연산(%)

실행 방법: python 02_rps_basic.py
"""

# =====================================================================
# 게임 규칙: 컴퓨터와 가위바위보를 해서 "먼저 2승" 하는 쪽이 이겨요.
#
# 핵심 아이디어: 승패를 if 문 9개로 따지지 않고 "수학"으로 판정해요.
#   choices = ["가위", "바위", "보"]  → 인덱스  0, 1, 2
#   (내 인덱스 - 컴퓨터 인덱스) % 3 의 값으로 판정
#       0 → 비김,  1 → 이김,  2 → 짐
#   예) 나: 바위(1), 컴퓨터: 가위(0) → (1 - 0) % 3 = 1 → 이김
#       나: 가위(0), 컴퓨터: 바위(1) → (0 - 1) % 3 = 2 → 짐
#   (파이썬에서 -1 % 3 은 2 예요. 나머지는 항상 0 이상이 되도록 계산돼요.)
#   → 각 선택이 "바로 앞의 것"을 이긴다는 원형(순환) 구조를 숫자로 표현한 것!
# =====================================================================

import random

choices = ["가위", "바위", "보"]   # 리스트: 여러 값을 순서대로 담는 상자
me = com = 0                       # 내 점수와 컴퓨터 점수를 둘 다 0으로 (연쇄 대입)

print("=== 가위바위보 === 먼저 2승 하면 이깁니다!")

# 논리 연산자 and: 두 조건이 "모두" 참일 때만 참
# → 둘 다 2승 미만인 동안 계속 경기
while me < 2 and com < 2:
    pick = input("가위 / 바위 / 보 > ")

    # in 연산자: 리스트 안에 값이 있는지 확인 (not in → 없으면 True)
    if pick not in choices:
        print("가위, 바위, 보 중에서 입력하세요!")
        continue

    cpu = random.choice(choices)          # 리스트에서 무작위로 하나 고르기
    print(f"나: {pick}  vs  컴퓨터: {cpu}")

    # index(값): 리스트에서 그 값이 몇 번째(0부터)에 있는지 알려 줌
    diff = (choices.index(pick) - choices.index(cpu)) % 3   # 0:비김 1:이김 2:짐

    if diff == 0:
        print("비겼어요!")
    elif diff == 1:
        print("이겼다!")
        me += 1
    else:
        print("졌다...")
        com += 1
    print(f"현재 점수  나 {me} : {com} 컴퓨터")

# 조건 표현식(삼항 연산자): A if 조건 else B → 조건이 참이면 A, 아니면 B
print("최종 승리!" if me == 2 else "아쉽게 패배...")
