"""기억력 게임 (기본 버전) - 7차시: 리스트 누적, 리스트 비교, 문자열 메서드, time 모듈

실행 방법: python 04_memory_basic.py
"""

# =====================================================================
# 게임 규칙
#   화면에 숫자들이 잠깐 보였다가 사라져요.
#   본 숫자를 순서대로 입력하면 다음 라운드로! 라운드마다 숫자가 1개씩 늘어나요.
#   한 번이라도 틀리면 게임 끝.
#
# 핵심 아이디어
#   - seq 리스트에 매 라운드 숫자를 하나씩 "누적(append)"
#   - 리스트끼리 == 로 비교하면 "개수와 순서와 값이 모두 같을 때" True
#
# ※ print("\n" * 40) 은 빈 줄 40개로 화면을 밀어 올려 "지운 것처럼" 보이게 해요.
#   IDLE 등 일부 환경에서는 스크롤을 올리면 보일 수 있어요. (게임의 한계 → 개선 아이디어!)
# =====================================================================

import random
import time          # time.sleep(초): 지정한 시간만큼 프로그램을 잠깐 멈춤

seq = []             # 기억해야 할 숫자 리스트 (매 라운드 1개씩 늘어남)
level = 0            # 성공한 라운드 수

print("=== 기억력 게임 === 화면에 나온 숫자를 기억해서 입력하세요!")

# while True: 조건이 항상 참 → 무한 반복. 안에서 break 를 만나야 끝나요.
while True:
    seq.append(random.choice("123456789"))   # 1~9 중 한 글자를 골라 리스트 끝에 추가

    # " ".join(seq): ['3','8'] → "3 8" (사이에 공백을 넣어 이어 붙임)
    print(f"\n[{len(seq)}라운드] 기억하세요:", " ".join(seq))
    time.sleep(1 + len(seq) * 0.5)         # 숫자가 길수록 오래 보여 줌 (1.5초, 2초, 2.5초 ...)
    print("\n" * 40)                       # 화면 지우기 (빈 줄 40개)

    # replace(" ", ""): 공백을 모두 없앰 → "3 8" 이라고 입력해도 "38" 로 처리
    guess = list(input("방금 본 숫자를 붙여서 입력 > ").replace(" ", ""))

    if guess == seq:                       # 리스트끼리 비교
        level += 1
        print("정답! 다음 라운드로!")
    else:
        print("틀렸어요! 정답은", "".join(seq))
        break

print(f"도전 결과: {level}라운드 성공!")
