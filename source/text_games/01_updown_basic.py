"""업다운 게임 (기본 버전) - 4차시: 변수, 조건문, while 반복문, 리스트 맛보기

실행 방법: 터미널에서  python 01_updown_basic.py
"""

# =====================================================================
# 이 게임은 어떻게 동작할까요?
# ---------------------------------------------------------------------
# 컴퓨터가 1~100 사이의 숫자 하나를 몰래 정해요.
# 플레이어는 7번 안에 그 숫자를 맞혀야 해요.
# 틀리면 컴퓨터가 "UP(더 큰 수)" 또는 "DOWN(더 작은 수)"을 알려 줘요.
#
# 입력 - 처리 - 출력 (IPO)
#   입력: 플레이어가 고른 숫자
#   처리: 정답과 비교 (같다 / 작다 / 크다), 범위 좁히기, 기회 줄이기
#   출력: "정답!", "UP!", "DOWN!", 실패 메시지
#
# ※ 18차시(테스트와 개선) 활동을 위해 일부러 남겨 둔 "숨은 문제"가 있어요.
#    범위 밖 숫자(예: 150)를 넣으면 어떻게 될까요? 직접 찾아보세요!
#    → 고친 버전은 11_updown_safe.py 에 있어요.
# =====================================================================

# random 모듈: 무작위 수를 만들 때 쓰는 파이썬 기본 도구
import random

# [1] 게임 준비 --------------------------------------------------------
secret = random.randint(1, 100)   # 1 이상 100 이하의 정수 하나를 무작위로 고름 (정답)
low, high = 1, 100                # 정답이 있을 수 있는 범위 (한 줄에 변수 2개 저장)
history = []                      # 내가 입력한 숫자를 차례대로 기록할 빈 리스트
chance = 7                        # 남은 기회

print("=== 업다운 === 1~100 사이의 숫자를 7번 안에 맞히세요!")

# [2] 게임 반복 --------------------------------------------------------
# while 조건: 조건이 True인 동안 들여쓰기 된 부분을 계속 반복해요.
while chance > 0:
    # f-문자열: 문자열 안의 { } 자리에 변수 값을 넣어 보여 줘요.
    text = input(f"[{low}~{high}] 남은 기회 {chance}회 > ")

    # isdigit(): 문자열이 숫자로만 되어 있으면 True
    # not 을 붙이면 반대 → "숫자가 아니라면"
    if not text.isdigit():
        print("숫자를 입력하세요!")
        continue                  # 아래 코드를 건너뛰고 반복의 처음으로 돌아감 (기회는 그대로!)

    guess = int(text)             # input()은 항상 문자열 → int()로 정수로 바꿔야 비교할 수 있어요.
    history.append(guess)         # append(): 리스트 맨 뒤에 값 추가
    chance -= 1                   # chance = chance - 1 과 같아요.

    # 다중 조건문: if → elif → else 중 "처음으로 참인 곳" 하나만 실행돼요.
    if guess == secret:
        # len(리스트): 리스트에 들어 있는 값의 개수
        print(f"정답! {len(history)}번 만에 맞혔어요. 기록: {history}")
        break                     # 반복문을 즉시 빠져나감 → 아래 else 는 실행되지 않아요.
    elif guess < secret:
        print("UP! 더 큰 수예요.")
        low = max(low, guess + 1)     # 범위를 좁혀 간다 (max: 둘 중 큰 값)
    else:
        print("DOWN! 더 작은 수예요.")
        high = min(high, guess - 1)   # min: 둘 중 작은 값

# [3] while ~ else --------------------------------------------------
# 반복이 break 없이 "조건이 거짓이 되어" 끝났을 때만 else 가 실행돼요.
# 즉, 기회를 모두 써 버렸을 때(실패)만 아래 문장이 출력됩니다.
else:
    print(f"실패! 정답은 {secret}, 기록: {history}")
