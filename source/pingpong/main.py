"""핑퐁 게임 실행 파일입니다. 이 파일을 실행하면 게임이 시작됩니다."""

# =====================================================================
# 이 파일(main.py)은 무슨 역할을 할까요?
# ---------------------------------------------------------------------
# main.py는 게임의 "시작 버튼"이에요.
# 실제 게임 규칙, 공, 패들, 점수 같은 내용은 다른 파일들에 나뉘어 있고,
# main.py는 그 게임을 "만들고(Game())" + "실행(run())"하는 일만 합니다.
#
# 게임 조작법
#   - 왼쪽 플레이어 : W(위), S(아래)
#   - 오른쪽 플레이어: ↑(위), ↓(아래)
#   - R 키: 다시 시작 / ESC 키 또는 창 닫기: 게임 종료
#   - 먼저 5점을 얻는 사람이 승리!
#
# 프로젝트 파일 구성 (역할 분담표)
#   main.py        → 게임 시작 버튼 (지금 보고 있는 파일)
#   game.py        → 게임 전체를 지휘하는 "감독" (Game 클래스)
#   paddle.py      → 플레이어가 움직이는 막대 (Paddle 클래스)
#   ball.py        → 튕겨 다니는 공 (Ball 클래스)
#   scoreboard.py  → 점수판과 안내 문구 (Scoreboard 클래스)
#   constants.py   → 화면 크기, 색, 속도 같은 "설정값" 모음
#
# 전체 실행 흐름 (위에서 아래로 순서대로 일어나요)
#   1) 터미널에서 `python main.py` 실행
#   2) 맨 아래 if __name__ == "__main__": 확인 → main() 함수 호출
#   3) main() 안에서 Game() 으로 게임 객체를 만듦
#        - pygame 준비, 800 x 500 크기의 창 만들기
#        - 왼쪽 패들, 오른쪽 패들, 공, 점수판 만들기
#   4) game.run() 으로 "게임 루프" 시작. 아래 과정을 1초에 60번 반복!
#        ① 입력 확인 (handle_events) : 창 닫기, ESC, R 키를 눌렀나?
#        ② 상태 업데이트 (update)     : 패들 이동, 공 이동, 벽/패들에 튕기기,
#                                       공이 화면 밖으로 나가면 상대방 +1점,
#                                       5점이 되면 승자 발표
#        ③ 화면 그리기 (draw)         : 배경 → 가운데 점선 → 점수 → 패들 → 공
#        ④ 잠깐 쉬기 (clock.tick)     : 1초에 60번(60 FPS)만 돌도록 속도 조절
#   5) ESC를 누르거나 창을 닫으면 반복이 멈추고 pygame이 종료됨
#
# 비유하자면: 플립북(종이 애니메이션)처럼
#    "조금 움직이고 → 한 장 그리고"를 아주 빠르게 반복해서
#    공과 패들이 부드럽게 움직이는 것처럼 보이게 만드는 거예요.
# =====================================================================


# ---------------------------------------------------------------------
# [1] 필요한 도구 가져오기 (import)
# ---------------------------------------------------------------------
# game.py 파일 안에 있는 Game 클래스를 가져옵니다.
# "from 파일이름 import 가져올것" 형식이에요. (파일 이름 뒤의 .py는 빼고 씁니다)
# 클래스(class)는 "설계도"라고 생각하면 돼요.
# Game 설계도에는 게임 창, 패들, 공, 점수판을 어떻게 만들고 움직일지가 적혀 있어요.
from game import Game


# ---------------------------------------------------------------------
# [2] main 함수 정의하기
# ---------------------------------------------------------------------
# def 는 "함수를 만든다(define)"는 뜻이에요.
# 함수는 여러 명령을 하나로 묶어 이름을 붙인 것이에요. (예: "라면 끓이기" 순서 묶음)
# 여기서는 함수를 "만들기만" 하고, 실제 실행은 맨 아래에서 main()을 부를 때 일어나요.
def main():
    # Game 설계도(클래스)로 실제 게임 하나를 만들어 game 이라는 변수에 저장합니다.
    # 설계도로 실제 물건을 만드는 것을 "객체(object)를 만든다"고 해요.
    # 이 순간 game.py의 __init__ 함수가 자동으로 실행되어
    # 게임 창, 양쪽 패들, 공, 점수판이 준비됩니다.
    game = Game()

    # 만들어 둔 게임을 실행합니다.
    # run() 안에는 "입력 확인 → 움직이기 → 그리기"를 반복하는 while 문이 있어서,
    # 게임이 끝날 때(ESC 또는 창 닫기)까지 이 줄에서 계속 머물러 있어요.
    game.run()


# ---------------------------------------------------------------------
# [3] 프로그램 시작 지점
# ---------------------------------------------------------------------
# __name__ 은 파이썬이 자동으로 만들어 주는 특별한 변수예요.
#   - 이 파일을 직접 실행하면 (python main.py) → __name__ 값은 "__main__"
#   - 다른 파일에서 import 해서 쓰면          → __name__ 값은 "main" (파일 이름)
# 즉, "이 파일을 직접 실행했을 때만 게임을 시작해라!" 라는 뜻이에요.
# 이렇게 해 두면 다른 파일이 이 파일을 가져다 쓸 때 게임이 갑자기 켜지는 일을 막을 수 있어요.
if __name__ == "__main__":
    main()  # 위에서 만든 main 함수를 호출(실행)합니다. → 게임 시작!