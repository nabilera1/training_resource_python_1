"""게임에서 자주 쓰는 숫자와 색을 한곳에 모아 둔 파일입니다."""

# =====================================================================
# 이 파일(constants.py)은 무슨 역할을 할까요?
# ---------------------------------------------------------------------
# 게임의 "설정표"예요. 화면 크기, 색깔, 속도, 승리 점수처럼
# 여러 파일에서 함께 쓰는 값을 한곳에 모아 두었어요.
#
# 왜 한곳에 모을까요?
#   예를 들어 공을 더 빠르게 하고 싶다면, 여러 파일을 뒤질 필요 없이
#   여기서 BALL_SPEED 숫자 하나만 바꾸면 게임 전체에 바로 적용돼요.
#
# 이름이 모두 대문자인 이유:
#   파이썬에서는 "게임 도중에 바뀌지 않는 값(상수, constant)"을
#   대문자 이름으로 쓰는 약속이 있어요. "이 값은 함부로 바꾸지 마세요"라는 표시예요.
#
# 다른 파일에서는 이렇게 가져다 써요:
#   from constants import SCREEN_WIDTH, BALL_SPEED
# =====================================================================


# ---------------------------------------------------------------------
# [1] 화면 설정
# ---------------------------------------------------------------------
# 화면 크기 (가로, 세로)
# 단위는 픽셀(pixel, 화면을 이루는 아주 작은 점)이에요.
SCREEN_WIDTH = 800   # 게임 창의 가로 길이: 800픽셀
SCREEN_HEIGHT = 500  # 게임 창의 세로 길이: 500픽셀
FPS = 60  # 1초에 화면을 그리는 횟수
#           FPS = Frames Per Second(초당 프레임 수).
#           60이면 1초에 그림을 60장 바꿔 그려서 움직임이 부드럽게 보여요.

# ---------------------------------------------------------------------
# [2] 색 설정
# ---------------------------------------------------------------------
# 색 (R, G, B)
# 컴퓨터는 빛의 3원색 빨강(R), 초록(G), 파랑(B)을 섞어서 색을 만들어요.
# 각 숫자는 0(전혀 없음) ~ 255(가장 밝음) 사이예요.
#   (0, 0, 0)       → 검정
#   (255, 255, 255) → 흰색
#   (255, 0, 0)     → 빨강
# 괄호로 묶인 값 묶음은 "튜플(tuple)"이라고 불러요.
BLACK = (18, 18, 24)          # 배경색: 완전한 검정보다 살짝 푸른빛이 도는 어두운 색
WHITE = (240, 240, 240)       # 점수 글자색: 눈이 덜 부신 밝은 흰색
GRAY = (90, 90, 110)          # 가운데 점선, 안내 문구 색
LEFT_COLOR = (80, 180, 255)   # 왼쪽 패들 색: 하늘색
RIGHT_COLOR = (255, 140, 90)  # 오른쪽 패들 색: 주황색
BALL_COLOR = (255, 230, 80)   # 공 색: 노란색

# ---------------------------------------------------------------------
# [3] 패들(플레이어가 움직이는 막대) 설정
# ---------------------------------------------------------------------
# 패들
PADDLE_WIDTH = 14    # 패들의 가로 두께: 14픽셀
PADDLE_HEIGHT = 90   # 패들의 세로 길이: 90픽셀 (길수록 공을 막기 쉬워져요)
PADDLE_SPEED = 7     # 키를 누르고 있을 때 한 프레임에 움직이는 거리: 7픽셀
#                      1초에 60프레임이니까, 1초에 약 7 x 60 = 420픽셀 움직여요.
PADDLE_MARGIN = 30  # 화면 가장자리에서 패들까지 거리

# ---------------------------------------------------------------------
# [4] 공 설정
# ---------------------------------------------------------------------
# 공
BALL_SIZE = 16   # 공의 지름: 16픽셀
BALL_SPEED = 6   # 공이 한 프레임에 움직이는 거리: 6픽셀 (크게 하면 게임이 어려워져요)

# ---------------------------------------------------------------------
# [5] 점수와 글자 설정
# ---------------------------------------------------------------------
# 점수
WIN_SCORE = 5        # 이 점수에 먼저 도달하면 승리!
FONT_SIZE = 48       # 점수 숫자의 글자 크기
INFO_FONT_SIZE = 22  # 조작법, 안내 문구의 글자 크기
