"""19차시 코딩 테스트 1: 난이도 설정 불러오기 (기본) - 정답 예시 코드

코드 안에 `LEVELS = {"쉬움": [4, 3], "보통": [6, 5], "어려움": [8, 7]}`(공 속도, AI 속도)를 두세요. 난이도 이름을 입력받아 `공 속도 ○, AI 속도 ○`를 출력하고, 없는 이름이면 `보통` 설정을 사용하되 첫 줄에 `알 수 없는 난이도: 보통으로 설정`을 출력하세요.
"""

LEVELS = {"쉬움": [4, 3], "보통": [6, 5], "어려움": [8, 7]}
name = input().strip()
if name not in LEVELS:
    print("알 수 없는 난이도: 보통으로 설정")
    name = "보통"
ball_speed, ai_speed = LEVELS[name]
print(f"공 속도 {ball_speed}, AI 속도 {ai_speed}")
