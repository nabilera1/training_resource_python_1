"""19차시 코딩 테스트 2: 게임 상태 전환기 (도전) - 정답 예시 코드

게임 상태는 `준비`에서 시작합니다. 명령 문자열의 글자마다 다음 규칙으로 상태를 바꾸고, 바뀔 때마다(바뀌지 않으면 출력 없음) 새 상태를 출력하세요. 규칙: 준비에서 S → 진행 / 진행에서 P → 일시정지 / 일시정지에서 P → 진행 / 진행에서 W → 종료 / 종료에서 R → 준비. 그 밖의 명령은 무시합니다.
"""

RULES = {
    ("준비", "S"): "진행",
    ("진행", "P"): "일시정지",
    ("일시정지", "P"): "진행",
    ("진행", "W"): "종료",
    ("종료", "R"): "준비",
}
state = "준비"
for cmd in input().strip():
    if (state, cmd) in RULES:
        state = RULES[(state, cmd)]
        print(state)
